#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

export const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
export const products = {
  novel: { bundleName: 'app.amber.novel', name: 'Amber 小说', description: '小说创作工作台' },
  deepread: { bundleName: 'app.amber.deepread.reader', name: 'Amber 深读', description: '深度阅读工作台' },
};

const excludedDirectories = new Set([
  'build', 'target', 'archives', 'node_modules', 'oh_modules', '.hvigor', '.git', '.idea', '.cxx',
  'signed', 'material', 'credentials', 'userdata', 'user-data', 'backups',
]);
const excludedFiles = /(?:^\.env(?:\.|$)|^\.ohpmrc$|^local\.properties$|^oh-package-lock\.json5$|^\.DS_Store$|\.(?:p12|p7b|cer|pem|key|keystore|jks|hap|app|sqlite3?|db|log)$)/i;

// Only checked-in project configuration is evaluated, in an isolated context with no host APIs.
// JSON5's unquoted keys, single quotes, comments and trailing commas are ordinary JS literals.
export function readConfiguration(file) {
  return vm.runInNewContext(`(${fs.readFileSync(file, 'utf8')}\n)`, Object.create(null), {
    timeout: 1000,
    contextCodeGeneration: { strings: false, wasm: false },
  });
}

function writeConfiguration(file, value) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, `${JSON.stringify(value, null, 2)}\n`);
}

function copySource(source, destination) {
  const stat = fs.lstatSync(source);
  // Dependency and external-data symlinks must be resolved by ohpm, never copied from the host.
  if (stat.isSymbolicLink()) return;
  const name = path.basename(source);
  if (stat.isDirectory()) {
    if (excludedDirectories.has(name)) return;
    fs.mkdirSync(destination, { recursive: true });
    for (const child of fs.readdirSync(source)) copySource(path.join(source, child), path.join(destination, child));
  } else if (stat.isFile() && !excludedFiles.test(name)) {
    fs.mkdirSync(path.dirname(destination), { recursive: true });
    fs.copyFileSync(source, destination);
    fs.chmodSync(destination, stat.mode & 0o777);
  }
}

function setString(file, name, value) {
  const resource = readConfiguration(file);
  const existing = resource.string.find((item) => item.name === name);
  if (existing) existing.value = value;
  else resource.string.push({ name, value });
  writeConfiguration(file, resource);
}

function sourceFiles(directory, prefix = '') {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((item) => {
    const relative = path.join(prefix, item.name);
    return item.isDirectory() ? sourceFiles(path.join(directory, item.name), relative) : [relative];
  });
}

function updateSnapshot(stage, output, previousFiles) {
  const currentFiles = sourceFiles(stage);
  const retained = new Set(currentFiles);
  // Only previously generated source files are retired. Build caches, ohpm dependencies,
  // locally generated signing material and unrelated new files remain untouched.
  for (const relative of previousFiles) {
    if (retained.has(relative)) continue;
    if (path.isAbsolute(relative) || relative.split(path.sep).includes('..')) throw new Error('Invalid generated source manifest');
    fs.rmSync(path.join(output, relative), { force: true });
  }
  for (const relative of currentFiles) {
    const source = path.join(stage, relative);
    const destination = path.join(output, relative);
    if (fs.existsSync(destination) && fs.readFileSync(source).equals(fs.readFileSync(destination))) continue;
    fs.mkdirSync(path.dirname(destination), { recursive: true });
    fs.copyFileSync(source, destination);
    fs.chmodSync(destination, fs.statSync(source).mode & 0o777);
  }
  return currentFiles;
}

export function selectProducts(args) {
  if (args.length !== 2 || args[0] !== '--product' || !['novel', 'deepread', 'all'].includes(args[1])) {
    throw new Error('Usage: node scripts/harmony-standalone/prepare.mjs --product novel|deepread|all');
  }
  return args[1] === 'all' ? Object.keys(products) : [args[1]];
}

export function prepareProduct(product, root = repositoryRoot) {
  const definition = products[product];
  if (!definition) throw new Error(`Unknown product: ${product}`);
  const source = path.join(root, 'harmony');
  const outputParent = path.join(root, '.harmony-standalone');
  const output = path.join(outputParent, product);
  const markerName = '.amber-product.json';
  let previousFiles = [];
  if (fs.existsSync(output)) {
    const marker = path.join(output, markerName);
    if (!fs.existsSync(marker) || JSON.parse(fs.readFileSync(marker, 'utf8')).product !== product) {
      throw new Error(`Refusing to replace a directory not generated by this script: ${output}`);
    }
    previousFiles = JSON.parse(fs.readFileSync(marker, 'utf8')).sourceFiles ?? [];
  }
  fs.mkdirSync(outputParent, { recursive: true });
  fs.writeFileSync(path.join(outputParent, '.gitignore'), '*\n');
  const stage = fs.mkdtempSync(path.join(outputParent, `.${product}-`));
  try {
    for (const name of ['AppScope', 'entry', 'chat', 'deepread', 'native', 'hvigor', 'hvigorfile.ts', 'oh-package.json5', 'code-linter.json5']) {
      if (fs.existsSync(path.join(source, name))) copySource(path.join(source, name), path.join(stage, name));
    }
    // Never copy the host's AGC credentials even temporarily into the generated project.
    const profile = readConfiguration(path.join(source, 'build-profile.json5'));
    delete profile.app.signingConfigs;
    for (const configuration of profile.app.products) delete configuration.signingConfig;
    writeConfiguration(path.join(stage, 'build-profile.json5'), profile);

    const appFile = path.join(stage, 'AppScope/app.json5');
    const app = readConfiguration(appFile);
    app.app.bundleName = definition.bundleName;
    writeConfiguration(appFile, app);
    setString(path.join(stage, 'AppScope/resources/base/element/string.json'), 'app_name', definition.name);
    const entryStrings = path.join(stage, 'entry/src/main/resources/base/element/string.json');
    for (const [name, value] of Object.entries({
      product_kind: product,
      EntryAbility_label: definition.name,
      EntryAbility_desc: definition.description,
      module_desc: definition.description,
      reason_internet: '用于连接 AI 服务和检索公开来源',
      reason_network: '用于检测网络连接状态',
    })) setString(entryStrings, name, value);

    const moduleFile = path.join(stage, 'entry/src/main/module.json5');
    const module = readConfiguration(moduleFile);
    const permissions = new Set([
      'ohos.permission.INTERNET', 'ohos.permission.GET_NETWORK_INFO',
      'ohos.permission.KEEP_BACKGROUND_RUNNING', 'ohos.permission.VIBRATE',
    ]);
    module.module.requestPermissions = module.module.requestPermissions.filter((item) => permissions.has(item.name));
    module.module.extensionAbilities = (module.module.extensionAbilities ?? []).filter((item) =>
      product === 'novel' && item.name === 'NovelPolishWorkAbility');
    writeConfiguration(moduleFile, module);
    // Keeping the signing script under the generated root makes its AppScope lookup product-specific.
    copySource(path.join(source, 'scripts/sign-hap.sh'), path.join(stage, 'scripts/sign-hap.sh'));
    const ownedFiles = updateSnapshot(stage, output, previousFiles);
    writeConfiguration(path.join(output, markerName), {
      product, bundleName: definition.bundleName, source: 'harmony', sourceFiles: ownedFiles,
    });
  } finally {
    fs.rmSync(stage, { recursive: true, force: true });
  }
  return output;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    for (const product of selectProducts(process.argv.slice(2))) console.log(`${product}: ${prepareProduct(product)}`);
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
