#!/usr/bin/env node
// gen-phosphor-icons.mjs — 拉取 phosphor-icons/core fill 字形,生成 ArkTS 路径表
// 输出: harmony/entry/src/main/ets/components/ui/phosphor_paths.ets
// 用法: node harmony/scripts/gen-phosphor-icons.mjs
//
// iOS 首页 HomePhosphor(fill 风格)同源字形;viewBox 0 0 256 256。
// 多 path 的 SVG 拼接为一个 commands 串(子路径)。

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const outFile = join(here, '../entry/src/main/ets/components/ui/phosphor_paths.ets');

// ph_ 后缀(Icon 名) → phosphor core 文件名(kebab, fill 目录)
const ICONS = [
  // chrome / shortcut / continue
  'magnifying-glass', 'gear', 'pencil', 'push-pin', 'book-open', 'notebook',
  'chat-circle-dots', 'squares-four', 'globe', 'image-square', 'clock', 'list',
  // catalog
  'moon', 'sun', 'wine', 'coffee', 'sword', 'crown', 'castle-turret',
  'list-checks', 'music-notes', 'headphones', 'map-pin', 'airplane', 'car',
  'train', 'pill', 'heartbeat', 'scales', 'gavel', 'books', 'code', 'robot',
  'brain', 'lightbulb', 'flask', 'game-controller', 'trophy', 'football',
  'basketball', 'heart', 'smiley', 'fire', 'lightning', 'drop', 'snowflake',
  'mountains', 'tree', 'flower', 'dog', 'cat', 'fish', 'fork-knife', 'pizza',
  'hamburger', 'cake', 'house', 'buildings', 'wallet', 'currency-cny',
  'chart-line-up', 'shopping-cart', 'gift', 'calendar', 'graduation-cap',
  'student', 'camera', 'film-slate', 'video-camera', 'phone', 'envelope',
  'bell', 'lock', 'key', 'translate', 'quotes', 'users', 'baby', 'rocket',
  'briefcase', 'handshake', 'yin-yang', 'ghost', 'alien', 'mask-happy',
  'palette', 'paint-brush', 'chat-circle',
  // settings iOS 对齐(2026-09-29):行图标统一 phosphor 族
  'circle-half', 'sliders-horizontal', 'laptop', 'database', 'terminal-window',
  'wrench', 'shield', 'hard-drives', 'cpu', 'arrows-clockwise', 'files',
  'clock-counter-clockwise', 'star', 'info',
];

const BASE = 'https://cdn.jsdelivr.net/gh/phosphor-icons/core@main/assets/fill';

const phName = (kebab) => 'ph_' + kebab.replace(/-([a-z])/g, (_m, c) => c.toUpperCase());

const fetchIcon = async (kebab) => {
  const url = `${BASE}/${kebab}-fill.svg`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${kebab}: HTTP ${res.status}`);
  const svg = await res.text();
  const paths = [...svg.matchAll(/<path[^>]*\bd="([^"]+)"/g)].map((m) => m[1].trim());
  if (paths.length === 0) throw new Error(`${kebab}: no <path d>`);
  const evenodd = /fill-rule="evenodd"/.test(svg);
  return { d: paths.join(' '), evenodd };
};

const results = [];
let failed = 0;
for (const kebab of ICONS) {
  try {
    const { d, evenodd } = await fetchIcon(kebab);
    results.push({ name: phName(kebab), d, evenodd });
  } catch (err) {
    failed++;
    console.error(`FAIL ${kebab}: ${err.message}`);
  }
}

const lines = [];
lines.push('// phosphor_paths.ets — GENERATED by harmony/scripts/gen-phosphor-icons.mjs,勿手改');
lines.push('// 字形来源: phosphor-icons/core (MIT) fill 风格, viewBox 0 0 256 256');
lines.push('// iOS HomePhosphor 同源; Icon.ets 以 ph_ 前缀消费');
lines.push('');
lines.push('export const phosphorPath = (name: string): string => {');
for (const r of results) {
  const note = r.evenodd ? ' // evenodd' : '';
  lines.push(`  if (name === '${r.name}') return '${r.d}';${note}`);
}
lines.push("  return '';");
lines.push('};');
lines.push('');
writeFileSync(outFile, lines.join('\n'));
console.log(`OK ${results.length} icons -> ${outFile} (${failed} failed)`);
const odd = results.filter((r) => r.evenodd).map((r) => r.name);
if (odd.length > 0) console.log(`evenodd icons (检查镂空渲染): ${odd.join(', ')}`);
